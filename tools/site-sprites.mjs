#!/usr/bin/env node
/**
 * Copies the pixel character from the app (src/avatar/sprites.ts) to the website
 * (site/sprites.js), so mritmo.com draws exactly the same character.
 * Run after changing the sprites: node tools/site-sprites.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'src/avatar/sprites.ts'), 'utf8');
const grab = (name) => {
  const m = src.match(new RegExp(`export const ${name}[^=]*=\\s*(\\{[\\s\\S]*?\\n\\})(?: as const)?;`));
  if (!m) throw new Error(`No encontré ${name} en sprites.ts`);
  return JSON.parse(m[1]);
};
const data = { sprites: grab('SPRITES'), colors: grab('SPRITE_COLORS') };
writeFileSync(
  join(root, 'site/sprites.js'),
  `// Generated by tools/site-sprites.mjs from src/avatar/sprites.ts. Do not edit by hand.\nwindow.MRITMO_SPRITES = ${JSON.stringify(data)};\n`,
);
console.log('site/sprites.js listo');
